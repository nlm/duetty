package app

import (
	"context"
	"errors"
	"fmt"
	"io"
	"time"

	"github.com/nlm/duetty/internal/config"
	"github.com/nlm/duetty/internal/ctxfile"
	"github.com/nlm/duetty/internal/translate"
)

// hintTimeout bounds one Whisper hint generation.
const hintTimeout = 30 * time.Second

// HintSource generates Whisper hints from a context body.
type HintSource interface {
	WhisperHints(ctx context.Context, body string, langs [2]string) (map[string]string, error)
}

// ResolveHints returns the Whisper hints for the pair: the file's own when it
// has any for a pair language (no call), else generated by gen with a 30 s
// timeout. Empty hint values count as absent.
func ResolveHints(ctx context.Context, f ctxfile.File, pair [2]string, gen HintSource) (hints map[string]string, generated bool, err error) {
	own := map[string]string{}
	for _, l := range pair {
		if h := f.Hints[l]; h != "" {
			own[l] = h
		}
	}
	if len(own) > 0 {
		return own, false, nil
	}
	ctx, cancel := context.WithTimeout(ctx, hintTimeout)
	defer cancel()
	hints, err = gen.WhisperHints(ctx, f.Body, pair)
	if err != nil {
		return nil, false, err
	}
	return hints, true, nil
}

// keyChecked checks the API keys right before a hint generation, so a file
// that already has hints needs none.
type keyChecked struct {
	cfg config.Config
	gen HintSource
}

func (k keyChecked) WhisperHints(ctx context.Context, body string, langs [2]string) (map[string]string, error) {
	if err := k.cfg.CheckKeys(); err != nil {
		return nil, err
	}
	return k.gen.WhisperHints(ctx, body, langs)
}

// PrintWhisperHints writes the hints for the configured pair as
// "### <code>" sections, ready to paste into the context file's
// "## Whisper hint" section. It needs -context.
func PrintWhisperHints(ctx context.Context, cfg config.Config, w io.Writer) error {
	if cfg.ContextFile == "" {
		return errors.New("-print-whisper-hint needs -context")
	}
	f, err := ctxfile.Load(cfg.ContextFile)
	if err != nil {
		return err
	}
	tc := translate.NewClient(cfg.TranslateURL(), cfg.TranslateKey(), cfg.TranslateModel)
	hints, _, err := ResolveHints(ctx, f, cfg.Languages, keyChecked{cfg, tc})
	if err != nil {
		return fmt.Errorf("whisper hint: %w", err)
	}
	for _, l := range cfg.Languages {
		if _, err := fmt.Fprintf(w, "### %s\n%s\n\n", l, hints[l]); err != nil {
			return err
		}
	}
	return nil
}
